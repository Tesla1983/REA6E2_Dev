/* ============================================================
 * 3.5" 屏接线自检 + 方案A 演示（P1 + P2 阶段的合并验证）
 *
 * 依次在屏幕上显示 6 个画面, 每个画面对应一种"接线正确"的判据:
 *   STAGE 1  全点亮（0xA5）      —— 屏亮 + 背光亮 + 初始化生效
 *   STAGE 2  全灭                —— RAM 清空通路正常
 *   STAGE 3  4px 竖条纹          —— SPI 数据通路正常（数据真的进了 RAM）
 *   STAGE 4  1px 棋盘格          —— 列/页映射正确（没有整列错位、没有丢页）
 *   STAGE 5  边框 + 文字          —— 列偏移(COL_OFFSET) 与起始行(START_LINE) 正确
 *   STAGE 6  方案 A 静态仪表盘     —— 4 行 x 16 字符布局效果（数据为演示值）
 *
 * 屏是只写器件, MCU 无法回读任何东西 —— 所以"接线是否正确"最终只能靠眼睛。
 * 本文件的作用是把"看到什么 = 哪一段对/不对"对应起来。
 * ============================================================ */
#ifndef NT7534_H_
#define NT7534_H_

#include <stdint.h>

/** 固件版本标记（ram 里的魔数）。
 *
 *  起因: 烧录 ≠ 运行。探针把 flash 写完但内核没复位时, 屏上仍是旧固件画的旧图像
 *  （LCD 会无限期保留), 于是"改了代码没生效"这类误判极难自证。
 *  现在 `NT7534_Run()` 一进来就写这个魔数, 一条命令即可判定:
 *      probe-rs read --chip R7FA6E2BB b32 <&g_nt_fw_tag> 1
 *  读到 != 0 且等于下面期望值 ⇒ 新固件真的在跑; 读到 0 ⇒ 内核从未执行到本函数。
 *
 *  版本历史: v1 = 首次接线自检; v2 = 起始行 0x20 -> 0x00;
 *            v3 = 每帧重申几何参数;
 *            v4 = 发送侧页旋转补偿 32 行 + 真实串口数据 + ℃ 合成字形 + 去掉心跳方块;
 *            v5 = ℃ 小圈移到 C 左上角（v4 在右上方, 目视偏右）;
 *            v6 = 界面改用 u8g2 绘制（字库自带真 ° 字形, 不再合成 ℃）;
 *            v7 = 数据通路换成 USB CDC(Type-C 虚拟串口), 时钟 20MHz 晶振->PLL 240->USBCLK 48;
 *            v8 = 屏上版本字样改为从 TAG 的低 8 位推出（v7 时它硬编码 "v6", 与魔数矛盾）;
 *            v9 = 链路不通时把画面让给"USB 中断三段自证"（IELSR0 / NVIC ISER0 / INTSTS0+INTENB0）;
 *            v10 = 诊断行补 PRIMASK（全局中断开关）, 并在 R_USB_Open 后强制补写 INTENB0=0x9D00。
 *            v11 = 0x22 SET_CONTROL_LINE_STATE 也补 pipe0 的 BEMPENB;
 *                  wValue 的 DTR 位改为运行时可调（实测 usbser 是 bit1=DTR, 与规范文字相反）。
 *            v12 = 类请求入口无条件开 pipe0 的 BRDYENB/BEMPENB; 加 SERIAL_STATE 运行时开关与事件时间线。
 *            v13 = **接收重挂移出回调**（原在 usb_callback 里调 R_USB_Read, FSP 禁止 ⇒ 静默失败,
 *                  导致只收到第一包就断流、屏上全 `--`）; 屏上状态行改为 linked / unlink,
 *                  并移除固件版本号显示。
 *                  注: v12 曾有两个不同变体（10-23 晚与 10-24 下午）, 故升 v13 消除歧义。
 *            v14 = 串口链路新增 `$ID?` 身份查询（芯片 UID 应答），
 *                  供上位机按板子唯一 ID 连接，不再依赖 COM 号。
 *                  应答: `$ID:RA6E2-<UID首尾字>,FW:<ver>*XX`。
 *            v15 = **0x22 不再碰 pipe0 中断**（v12 的"无条件开 BEMPENB"已证伪：补丁在板上
 *                  跑了三天, SETDTR 仍卡 30.00 s）; 0x21/0x20 改为"先清陈旧
 *                  BRDYSTS/BEMPSTS 再开使能"; 新增控制传输阶段 CTSQ 采样诊断。
 *            v16 = **30 s 根因修复**：无数据类请求（0x22）补上 FSP 漏掉的
 *                  `PID=BUF`（等价 usb_cstd_set_buf(pipe0)）。缺这一步时状态阶段的
 *                  0 长度 IN 包发不出去，CTSQ 恒停 5 ⇒ usbser 等满 30 s。
 *            v17 = **USB 提前初始化**：原来 USB_CDC_Init() 排在 6 段屏幕自检之后
 *                  （光等待就 13.7 s）⇒ 拔插/复位后要十几秒主机才看得到设备。
 *                  现在 USB 在自检前起来，且 stage_wait 每 2 ms 排空 USB 事件。
 *            v18 = **屏幕自检改为宏开关 （默认 0 = 关闭）**：
 *                  自检那 13.7 s 停顿不再占用开机时间，USB 约 1 s 内即可枚举；
 *                  换屏/改接线时把开关置 1 即可复现 5 段画面与引脚自检。
 *            v19 = **表格版界面 + 右下角双风扇**：4x4 网格(CPU/GPU/RAM/linked)，
 *                  单元格文字居中，右下角两个风扇格标 CPU/GPU，3 叶 20x20；
 *                  风扇按 cf/gf RPM 实时转动(DWT 时基 ~25 Hz)，与上位机送数频率解耦；
 *                  unlink 时风扇照常显示但静止。
 *            v20 = **表格加宽/上移**：右边界 119→124（用掉右侧 8px 空白中的 5px），
 *                  风扇格/数值格随之右移；显示起始行 0→3（试填顶部约 3px 空白）。
 *                  风扇动画改脏区刷新，帧率 30→62fps。
 *            v21 = **版面微调**：右边界 124→125（右侧余 2px）；显示起始行 3→1
 *                  （3 行顶过头了，1 行刚好）。
 *            v22 = **贴边版**：起始行 1→0（1 行也顶过头，本屏无可用空行）；
 *                  右边界 125→127（横线 128px，表格贴到最右一列）。
 *            v23 = **动画帧只重画风扇格**：不再整屏重画，主循环从 ~2.5 s 回到 ~1 s，
 *                  数字/状态恢复真正 1 Hz 刷新；动画只脏刷右下两格。
 *            v24 = **改用内核 SysTick 做 1 ms 真实时基**（DWT CYCCNT 后实测本 M33 可用，但 SysTick 法已够直观）：
 *                  主循环按 1000 ms 定拍（原来 500 片 × 2 ms 实际 ~1.7 s ⇒ 数字只有
 *                  ~0.6 Hz）；风扇每 16 ms 一帧、相位按真实 dt×1.5 推进。
 *            v25 = **状态行中英文跟随上位机**：新增协议字段 `LG:0/1`（1=中文），
 *                  固件存 `g_screen_lang`（默认中文，不随断链清零），状态行按语言显示
 *                  「已连接 / 未连接」（16x15 宋体点阵，4 字 120 B）或 `linked / unlink`。 */
extern volatile uint32_t g_nt_fw_tag;

/** 与 `g_nt_fw_tag` 对应的期望值（"NT" + 版本号）。改代码时同步 +1。 */
#define NT7534_FW_TAG   (0x4E54001Bu)

/** 版本号字节 —— 从 `NT7534_FW_TAG` 低 8 位取。
 *  起因: v6 -> v7 时屏上状态行是硬编码字符串, 改版忘了改 ⇒ 探针读到 0x4E540007、
 *  屏上却仍印着 "v6", 两条判据当场互相矛盾。现在只有一处真值, 改 TAG 即全同步。
 *  ⚠ v13 起**屏上不再显示版本号**（按需求改成 linked/unlink）,
 *    但 RTT 日志里仍会打印, 探针也仍可读 `g_nt_fw_tag` —— 版本判据只看魔数即可。 */
#define NT7534_FW_VER   ((unsigned) (NT7534_FW_TAG & 0xFFu))

/** 跑完整套自检 + 方案A, 内部是死循环, 不返回。
 *  g_nt_probe_bad > 0（信号线被拉低）时不驱动任何引脚, 只快闪 LED 报错。 */
void NT7534_Run(void);

#endif /* NT7534_H_ */

/** 3.5" 屏开机自检开关。
 *
 *  `0`（默认）= 开机直接进版面 A 主循环 —— USB 约 1~2 s 内可枚举。
 *  `1`         = 开机先跑 5 段接线自检（全亮/全灭/条纹/棋盘/边框），约 14 s。
 *
 *  什么时候打开：换屏、改接线、怀疑列偏移/起始行不对时。
 *  ⚠ 打开后开机变慢（自检期间会持续排空 USB 事件，所以枚举本身不受影响）。
 *  ⚠ 自检代码在 `#if (0 != NT7534_SELFTEST)` 里，**关闭时不参与编译**；
 *     如果你动了 `NT7534_*` 或 `OLED_*` 的接口，记得把开关打开编一次再关回去。
 */
#define NT7534_SELFTEST   (0)
