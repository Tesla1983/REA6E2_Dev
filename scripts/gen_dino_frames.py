CACTUS_HEIGHTS = [26, 29, 32]


def scale_rows(rows, h):
    """把 35 行垂直最近邻缩放到 h 行(保持轮廓完整, 不做断头裁剪)。"""
    src = len(rows)
    if h == src:
        return rows
    out = []
    for y in range(h):
        sy = int(round(y * (src - 1) / (h - 1))) if h > 1 else 0
        out.append(rows[max(0, min(src - 1, sy))])
    return out


def scale_2d(rows, nw, nh):
    """2D 最近邻缩放(云用): 输出 nh 行、每行 nw 像素。"""
    sh = len(rows)
    sw = len(rows[0]) if sh else 0
    out = []
    for y in range(nh):
        sy = max(0, min(sh - 1, int(round(y * (sh - 1) / (nh - 1))) if nh > 1 else 0))
        line = []
        for x in range(nw):
            sx = max(0, min(sw - 1, int(round(x * (sw - 1) / (nw - 1))) if nw > 1 else 0))
            line.append(rows[sy][sx])
        out.append(''.join(line))
    return out


def pack(rows, w, h):
    bpr = (w + 7) // 8
    out = []
    for y in range(h):
        line = rows[y]
        for bx in range(bpr):
            v = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < w and line[x] == '#':
                    v |= (1 << bit)
            out.append(v)
    return out


def emit(path):
    nbytes = ((DINO_W + 7) // 8) * DINO_H
    L = []
    L.append('/* 自动生成，勿手改：scripts/gen_dino_frames.py （源: Chrome 100-offline-sprite.png 1x） */')
    L.append('#ifndef DINO_FRAMES_H')
    L.append('#define DINO_FRAMES_H')
    L.append('#include <stdint.h>')
    L.append('')
    L.append('#define DINO_W %d' % DINO_W)
    L.append('#define DINO_H %d' % DINO_H)
    L.append('#define DINO_FRAME_COUNT 2')
    L.append('#define DINO_FRAME_BYTES %d' % nbytes)
    L.append('static const uint8_t g_dino_frames[DINO_FRAME_COUNT][DINO_FRAME_BYTES] = {')
    for rows in DINO_FRAMES[:2]:
        data = pack(rows, DINO_W, DINO_H)
        L.append('  { ' + ', '.join('0x%02X' % v for v in data) + ' },')
    L.append('};')
    L.append('')
    L.append('/* 跳跃姿势(官方 frame: 双腿着地, 抬头) */')
    L.append('static const uint8_t g_dino_jump[DINO_FRAME_BYTES] = {')
    data = pack(DINO_FRAMES[2], DINO_W, DINO_H)
    L.append('  ' + ', '.join('0x%02X' % v for v in data))
    L.append('};')
    L.append('')
    L.append('#define CACTUS_N %d' % len(CACTUS_HEIGHTS))
    L.append('#define CACTUS_W %d' % CACTUS_W)
    L.append('/* 三档仙人掌高度(px), 均 <=32 保证顶端不超过恐龙嘴(y30) */')
    L.append('static const uint8_t g_cactus_hs[CACTUS_N] = { %s };'
             % ', '.join(str(h) for h in CACTUS_HEIGHTS))
    for idx, h in enumerate(CACTUS_HEIGHTS):
        data = pack(scale_rows(CACTUS, h), CACTUS_W, h)
        L.append('static const uint8_t g_cactus_%d[%d] = {' % (idx, len(data)))
        L.append('  ' + ', '.join('0x%02X' % v for v in data))
        L.append('};')
    L.append('static const uint8_t * const g_cactus_bmp[CACTUS_N] = { %s };'
             % ', '.join('g_cactus_%d' % i for i in range(len(CACTUS_HEIGHTS))))

    L.append('')
    L.append('#define CLOUD_N %d' % len(CLOUD_SIZES))
    L.append('static const uint8_t g_cloud_ws[CLOUD_N] = { %s };'
             % ', '.join(str(cw) for cw, chh in CLOUD_SIZES))
    L.append('static const uint8_t g_cloud_hs[CLOUD_N] = { %s };'
             % ', '.join(str(chh) for cw, chh in CLOUD_SIZES))
    for idx, (cw, chh) in enumerate(CLOUD_SIZES):
        data = pack(scale_2d(CLOUD, cw, chh), cw, chh)
        L.append('static const uint8_t g_cloud_%d[%d] = {' % (idx, len(data)))
        L.append('  ' + ', '.join('0x%02X' % v for v in data))
        L.append('};')
    L.append('static const uint8_t * const g_cloud_bmp[CLOUD_N] = { %s };'
             % ', '.join('g_cloud_%d' % i for i in range(len(CLOUD_SIZES))))
    L.append('')
    L.append('#endif /* DINO_FRAMES_H */')
    txt = '\n'.join(L) + '\n'
    with open(path, 'w', encoding='utf-8') as f:
        f.write(txt)
    print('OK ->', path, 'dino_frame_bytes=%d cactus_kinds=%d' % (nbytes, len(CACTUS_HEIGHTS)))


